using BubuUI;
using BubuUI.Elements;
using BubuUI.Rendering;
using BubuUI.Text.Shaping;
using BubuUI.Themes.Fluent;
using Gallery;

var shot = args.Length > 0 ? args[0] : "out/controls.png";
using var shaper = TextShaperFactory.TryCreate();
using var textPainter = shaper is null ? null : new HarfBuzzTextPainter(shaper);
ITextPainter text = textPainter is null ? new MeasuringTextPainter() : textPainter;
if (textPainter is not null) TextMeasurer.Current = textPainter;
using var page = new FluentGalleryPage();
page.EnsureInitialized();
var painter = new ElementPainter(FluentTheme.Light, text);
painter.Prepare(page);
using var host = new HeadlessRoot(page) { AvailableSize = new(720, 960) };
host.UpdateLayout();
void Check(bool condition, string message) { if (!condition) throw new InvalidOperationException(message); }
var button = page.LiveControls.OfType<Button>().First();
var point = button.PointFromRoot(Point.Zero);
point = new(-point.X + 10, -point.Y + 12);
host.Input.PointerPress(point); host.Input.PointerRelease(point);
Check(page.Status == "Button clicked 1 time", "Button input did not update status.");
var editor = page.LiveControls.OfType<TextBox>().First();
host.Focus.Focus(editor); editor.SelectAll(); host.Input.TextInput("Unicode + 中文 😀 👩‍💻 👍🏽 ❤️ 🎉"); host.UpdateLayout();
Check(editor.Text == "Unicode + 中文 😀 👩‍💻 👍🏽 ❤️ 🎉", "Text input failed.");
var slider = page.LiveControls.OfType<Slider>().Single();
slider.Value = 75;
Check(page.LiveControls.OfType<ProgressBar>().Single().Value == 75, "Slider/progress binding failed.");
var combo = page.LiveControls.OfType<ComboBox>().Single();
combo.SelectedIndex = 1; combo.IsDropDownOpen = true; host.UpdateLayout();
Check(painter.Build(page, host.AvailableSize).Validate().Count == 0, "Open popup display list was invalid.");
page.ResetControls(); host.UpdateLayout();
Check(combo.IsDisposed && page.Status == "Ready to explore", "Reset did not release controls and restore status.");
Check(page.LiveControls.OfType<Slider>().Single().Value == 40, "Reset did not restore values.");
GallerySnapshot.SavePng(page, host.AvailableSize, 1, shot, FluentTheme.Light, text);
Console.WriteLine($"Fluent input, values, popup and reset passed: {shot}");
