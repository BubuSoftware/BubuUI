using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using EclipseUI.Compiler;

namespace EclipseUI.Compiler.Generator;

/// <summary>
/// 代码发射：把模板 AST 翻译成组件构建代码。
/// 生成代码 = 结构创建指令 + 根级 U{N}/块内 R{N} 定向更新 + 块协调器接线；
/// 表达式行用 #line 指向 .ui 源位置（诊断与断点映射共用）。
/// </summary>
public sealed class Emitter
{
    private enum EmitMode { Root, Block, Content }

    private sealed class EmitContext
    {
        public EmitMode Mode { get; init; }
        public string? ScopeVar { get; init; }

        /// <summary>内容模式下接收方组件（TrackContent 目标，spec/02 §4.12.3）。</summary>
        public string? ContentReceiver { get; init; }

        public bool IsRoot => Mode == EmitMode.Root;
        public bool IsContent => Mode == EmitMode.Content;

        public static EmitContext Root() => new() { Mode = EmitMode.Root };

        public static EmitContext Block(string scopeVar)
            => new() { Mode = EmitMode.Block, ScopeVar = scopeVar };

        public static EmitContext Content(string receiver)
            => new() { Mode = EmitMode.Content, ContentReceiver = receiver };
    }

    private sealed record FieldDecl(int N, string Prefix, string Type);
    private sealed record UMethod(string Name, string Body);

    private readonly UiDocument _doc;
    private readonly string _accessibility;
    private readonly string _namespace;
    private readonly string _className;
    private readonly Dictionary<UiForeach, string> _itemTypes;
    private readonly string _linePath;
    private readonly StringBuilder _sb = new();
    private readonly StringBuilder _body = new();
    private readonly List<FieldDecl> _fields = new();
    private readonly List<UMethod> _uMethods = new();
    private readonly List<string> _renderCalls = new();
    private StringBuilder _out = null!;
    private int _indent;
    private int _varCounter;
    private int _fnCounter;

    public Emitter(UiDocument doc, string accessibility, string namespaceName, string className,
        Dictionary<UiForeach, string> itemTypes, string filePath)
    {
        _doc = doc;
        _accessibility = accessibility;
        _namespace = namespaceName;
        _className = className;
        _itemTypes = itemTypes;
        // #line 的文件名不是 C# 字符串字面量：反斜杠原样写入，否则映射路径会变成双反斜杠。
        _linePath = filePath.Replace("\"", "\\\"");
    }

    public string Emit()
    {
        var root = (UiElement)_doc.Nodes.First(n => n is UiElement);
        _out = _body;
        _indent = 2;
        var rootVar = EmitElement(root, parentVar: null, EmitContext.Root());
        Line($"return {rootVar};");

        _out = _sb;
        _indent = 0;
        _sb.AppendLine("// <auto-generated> 由 EclipseUI 模板编译器生成；请勿手动修改。 </auto-generated>");
        _sb.AppendLine("#nullable enable");
        if (_namespace.Length > 0)
        {
            _sb.AppendLine($"namespace {_namespace};");
            _sb.AppendLine();
        }
        _sb.AppendLine($"{_accessibility} partial class {_className} : global::EclipseUI.Component");
        _sb.AppendLine("{");

        foreach (var field in _fields.OrderBy(f => f.N))
            _sb.Append("    private ").Append(field.Type).Append(" __").Append(field.Prefix).Append(field.N)
                .AppendLine(" = null!;");
        if (_fields.Count > 0) _sb.AppendLine();

        _sb.AppendLine("    protected override global::EclipseUI.Element Build()");
        _sb.AppendLine("    {");
        _sb.Append(_body);
        _sb.AppendLine("    }");

        if (_renderCalls.Count > 0)
        {
            _sb.AppendLine();
            _sb.AppendLine("    protected override void Render()");
            _sb.AppendLine("    {");
            foreach (var call in _renderCalls)
                _sb.Append("        ").AppendLine(call);
            _sb.AppendLine("    }");
        }

        foreach (var method in _uMethods)
        {
            _sb.AppendLine();
            _sb.Append("    private void ").Append(method.Name).AppendLine("()");
            _sb.AppendLine("    {");
            _sb.Append(method.Body);
            _sb.AppendLine("    }");
        }

        _sb.AppendLine("}");
        return _sb.ToString();
    }

    private string NewVar(string prefix) => $"{prefix}{_varCounter++}";

    private void Line(string text)
    {
        _out.Append(' ', _indent * 4).AppendLine(text);
    }

    /// <summary>表达式行映射到 .ui 源行；随后 hidden，使未映射行指回生成文件。</summary>
    private void Mapped(int uiLine, string text)
    {
        _out.Append("#line ").Append(uiLine).Append(" \"").Append(_linePath).Append('"').AppendLine();
        Line(text);
        _out.AppendLine("#line hidden");
    }

    /// <summary>
    /// 根级动态构造写入实例方法，局部变量不可捕获；只提升真正被 U 写入的元素/run。
    /// </summary>
    private static bool NeedsElementField(UiElement element, EmitContext ctx)
    {
        if (!ctx.IsRoot) return false;
        var dynamicAttr = element.Attributes.Any(attr =>
            attr.PropDef is not null && !attr.IsBind && attr.Name != "Key" &&
            attr.Kind == AttrValueKind.Expression);
        if (dynamicAttr) return true;
        return element.ResolvedDef!.Content == UiContentModel.Text &&
               element.Children.OfType<UiText>().SelectMany(t => t.Segments)
                   .Any(s => s.Kind == TextSegmentKind.Expression);
    }

    private string DeclareElement(UiElement element, EmitContext ctx)
    {
        var clrType = element.ResolvedDef!.ClrTypeDisplayName;
        var n = _varCounter++;
        if (NeedsElementField(element, ctx))
        {
            _fields.Add(new FieldDecl(n, "el", clrType));
            var field = $"__el{n}";
            Line($"{field} = new {clrType}();");
            return field;
        }

        var local = $"el{n}";
        Line($"var {local} = new {clrType}();");
        return local;
    }

    private string CreateU(string target, string body, int uiLine)
    {
        var name = $"U{_fnCounter++}";
        var sb = new StringBuilder();
        var savedOut = _out;
        var savedIndent = _indent;
        _out = sb;
        _indent = 2;
        Mapped(uiLine, $"{target} = {body};");
        _out = savedOut;
        _indent = savedIndent;
        _uMethods.Add(new UMethod(name, sb.ToString()));
        return name;
    }

    /// <summary>组件级动态写入：U 方法 + Build 首次调用 + Render 登记。</summary>
    private void RootUpdate(string target, string body, int uiLine)
    {
        var name = CreateU(target, body, uiLine);
        Line($"{name}();");
        _renderCalls.Add($"{name}();");
    }

    /// <summary>块内动态写入：R 局部函数 + 首次调用 + 作用域渲染动作。</summary>
    private void BlockUpdate(string target, string body, int uiLine, EmitContext ctx)
    {
        var name = $"R{_fnCounter++}";
        var sb = new StringBuilder();
        var savedOut = _out;
        var savedIndent = _indent;
        _out = sb;
        _indent = savedIndent + 1;
        Mapped(uiLine, $"{target} = {body};");
        _out = savedOut;
        _indent = savedIndent;

        Line($"void {name}()");
        Line("{");
        _out.Append(sb);
        Line("}");
        Line($"{name}();");
        Line($"{ctx.ScopeVar}.AddRenderAction({name});");
    }

    /// <summary>块内无用户表达式的刷新动作（绑定 Refresh / 嵌套块 Refresh）。</summary>
    private void BlockRefresh(string target, EmitContext ctx)
    {
        var name = $"R{_fnCounter++}";
        Line($"void {name}()");
        Line("{");
        _indent++;
        Line($"{target}.Refresh();");
        _indent--;
        Line("}");
        Line($"{name}();");
        Line($"{ctx.ScopeVar}.AddRenderAction({name});");
    }

    /// <summary>目录尚无处理器委托类型元数据（C3）；按 lambda 形态选择 AddHandler 的两个重载。</summary>
    private static string EventHandlerType(string expression)
    {
        var match = Regex.Match(expression.Trim(), @"^(?:async\s+)?(?:\(([^)]*)\)|([A-Za-z_]\w*))\s*=>");
        if (!match.Success) return "global::System.Action";
        if (match.Groups[1].Success && match.Groups[1].Value.Trim().Length == 0)
            return "global::System.Action";
        return "global::System.Action<global::EclipseUI.RoutedEventArgs>";
    }

    private int LineOf(TextSpan span) => _doc.Lines.LineOf(span.Start);

    private string EmitElement(UiElement element, string? parentVar, EmitContext ctx)
    {
        var def = element.ResolvedDef!;
        if (def.Origin == UiElementOrigin.Component)
            return EmitComponent(element, parentVar, ctx);
        var v = DeclareElement(element, ctx);

        foreach (var attr in element.Attributes)
        {
            if (attr.Name == "Key") continue;
            int line = LineOf(attr.ValueSpan.Length > 0 ? attr.ValueSpan : attr.NameSpan);

            // C5：Ref（spec/02 §4.14）——Build 时把元素实例赋给 code-behind 字段（源码顺序位置）。
            if (attr.RefTarget is { } refField)
            {
                Mapped(line, $"{refField} = {v};");
                continue;
            }

            if (attr.EventDef is { } evt)
            {
                var handlerType = EventHandlerType(attr.Value);
                var h = $"h{_varCounter++}";
                Mapped(line, $"var {h} = ({handlerType})({attr.Value.Trim()});");
                var wrapper = handlerType == "global::System.Action"
                    ? $"() => {{ {h}(); Invalidate(); }}"
                    : $"e => {{ {h}(e); Invalidate(); }}";
                Line($"{v}.AddHandler({evt.DeclaringTypeName}.{evt.FieldName}, {wrapper});");
            }
            else if (attr.PropDef is null)
            {
                // 未解析属性：Analyzer 已报 EUI002
            }
            else if (attr.IsBind)
            {
                EmitBinding(attr, attr.PropDef, v, ctx);
            }
            else if (attr.Kind == AttrValueKind.Literal)
            {
                Mapped(line, $"{v}.{attr.Name} = {attr.ConvertedLiteral};");
            }
            else
            {
                EmitDynamicUpdate(attr.Value, attr.ValueSpan, ctx, $"{v}.{attr.Name}", interpolate: false);
            }
        }

        switch (def.Content)
        {
            case UiContentModel.TextRuns:
                EmitTextRuns(element, v, ctx);
                break;
            case UiContentModel.Text:
                EmitLabel(element, v, def, ctx);
                break;
            case UiContentModel.Children:
                foreach (var child in element.Children)
                    EmitContainerChild(child, v, ctx);
                break;
        }

        if (parentVar is not null)
            Line($"{parentVar}.Children.Add({v});");
        return v;
    }

    /// <summary>
    /// 组件标签（spec/02 §4.12）：顺序固定 new → 作用域登记 → 参数（源码顺序）→ 内容 → Mount() → 挂父级。
    /// 参数形态：字面量 §4.2、动态推送 §4.3.3（U{N}/R{N} + EqualityComparer 保护）、
    /// 委托事件 §4.6.2、@bind 回调+推送 §4.4.3、默认内容 §4.12.3。
    /// </summary>
    private string EmitComponent(UiElement element, string? parentVar, EmitContext ctx)
    {
        var def = element.ResolvedDef!;
        var clrType = def.ClrTypeDisplayName;

        // 字段提升：根级存在动态参数（推送 U 捕获组件变量）或 @bind 推送时需要字段；
        // 委托参数/字面量是 build-once，局部即可；块/内容内一律局部（§4.4.3 规则 5）。
        bool needsField = ctx.IsRoot && element.Attributes.Any(attr =>
            attr.ParamDef is { IsDelegate: false, IsContent: false } && (attr.IsBind ||
                (!attr.IsBind && attr.Kind == AttrValueKind.Expression)));
        var n = _varCounter++;
        string v;
        if (needsField)
        {
            _fields.Add(new FieldDecl(n, "cmp", clrType));
            v = $"__cmp{n}";
            Line($"{v} = new {clrType}();");
        }
        else
        {
            v = $"cmp{n}";
            Line($"var {v} = new {clrType}();");
        }

        // 作用域登记（§4.12.1 规则 2）：登记在参数/内容之前。
        if (ctx.IsContent)
            Line($"{ctx.ContentReceiver}.TrackContent({v});");
        else if (ctx.IsRoot)
            Line($"Track({v});");
        else
        {
            Line($"Adopt({v});");
            Line($"{ctx.ScopeVar}.AddDisposable({v});");
        }

        foreach (var attr in element.Attributes)
        {
            if (attr.Name == "Key") continue; // EUI010 已报
            // C5：Ref（spec/02 §4.14）——组件按实例赋给 code-behind 字段（design/14 §14.6.4）。
            if (attr.RefTarget is { } refField)
            {
                Mapped(LineOf(attr.ValueSpan.Length > 0 ? attr.ValueSpan : attr.NameSpan),
                    $"{refField} = {v};");
                continue;
            }
            var p = attr.ParamDef;
            if (p is null) continue;          // 未解析名 EUI002 / 保留语法已报
            if (p.IsContent) continue;        // P= 写内容参数 EUI021 已报；内容由子节点提供
            int line = LineOf(attr.ValueSpan.Length > 0 ? attr.ValueSpan : attr.NameSpan);

            if (p.IsDelegate)
            {
                // 委托参数 = 事件（§4.6.2）：表达式 → h{N}，包装赋值 + Invalidate() 父组件。
                if (attr.IsBind || attr.Kind != AttrValueKind.Expression) continue; // EUI004/EUI040 已报
                var h = $"h{_varCounter++}";
                Mapped(line, $"var {h} = ({p.ClrTypeDisplayName})({attr.Value.Trim()});");
                var parms = string.Join(", ", Enumerable.Range(0, p.DelegateArity).Select(i => $"a{i}"));
                var invoke = p.DelegateArity == 0 ? $"{h}()" : $"{h}({parms})";
                var wrapper = p.DelegateArity == 0
                    ? $"() => {{ {invoke}; Invalidate(); }}"
                    : $"{parms} => {{ {invoke}; Invalidate(); }}";
                Line($"{v}.{p.Name} = {wrapper};");
            }
            else if (attr.IsBind && p.ChangedCallbackName is not null)
            {
                // §4.4.3：先赋 {P}Changed 回调（build-once），再在源码位置推送 U{N}/R{N}。
                var expression = attr.Value.Trim();
                Mapped(line, $"{v}.{p.ChangedCallbackName} = v =>");
                Line("{");
                _indent++;
                Line($"if (!global::System.Collections.Generic.EqualityComparer<{p.ClrTypeDisplayName}>.Default.Equals({expression}, v))");
                Line("{");
                _indent++;
                Mapped(line, $"{expression} = v;");
                Line("Invalidate();");
                _indent--;
                Line("}");
                _indent--;
                Line("};");
                EmitParamPush(p, v, attr.Value, line, ctx);
            }
            else if (!attr.IsBind && attr.Kind == AttrValueKind.Literal)
            {
                if (attr.ConvertedLiteral is null) continue; // EUI003 已报
                Mapped(line, $"{v}.{p.Name} = {attr.ConvertedLiteral};");
            }
            else if (attr.Kind == AttrValueKind.Expression)
            {
                if (ctx.IsContent)
                {
                    // 内容内 P={expr} 是 Build 快照（§4.12.3 规则 8）
                    Mapped(line, $"{v}.{p.Name} = ({p.ClrTypeDisplayName})({attr.Value.Trim()});");
                    continue;
                }
                EmitParamPush(p, v, attr.Value, line, ctx);
            }
            // @bind 无回调 / 字面量写委托参数 / :bind 等非法形态：Analyzer 已报，不生成
        }

        // 默认内容（§4.12.3）：build-once 静态展开到 List<Element>，再单根/多根赋参数。
        var contentParam = def.Parameters.Values.FirstOrDefault(p => p.IsContent);
        if (contentParam is not null)
        {
            var hasContent = element.Children.Any(c => c is UiElement or UiIf or UiForeach);
            var ck = $"content{_varCounter++}";
            Line($"var {ck} = new global::System.Collections.Generic.List<global::EclipseUI.Element>();");
            if (hasContent)
                EmitContentChildren(element.Children, ck, EmitContext.Content(v));
            var single = $"{ck}.Count == 0 ? null : {ck}[0]";
            Line($"{v}.{contentParam.Name} = {(contentParam.ContentIsMultiple ? ck : single)};");
        }

        Line($"{v}.Mount();");

        if (parentVar is not null)
            Line($"{parentVar}.Children.Add({v}.Root);");
        return $"{v}.Root";
    }

    /// <summary>组件参数动态推送（§4.3.3）：相等保护下写参数并失效子组件；根级 U{N}、块级 R{N}。</summary>
    private void EmitParamPush(UiParameterDef p, string target, string expression, int uiLine, EmitContext ctx)
    {
        var type = p.ClrTypeDisplayName;
        if (ctx.IsRoot)
        {
            var name = $"U{_fnCounter++}";
            var sb = new StringBuilder();
            var savedOut = _out;
            var savedIndent = _indent;
            _out = sb;
            _indent = 2;
            Mapped(uiLine, $"var v = ({type})({expression.Trim()});");
            Line($"if (!global::System.Collections.Generic.EqualityComparer<{type}>.Default.Equals({target}.{p.Name}, v))");
            Line("{");
            _indent++;
            Mapped(uiLine, $"{target}.{p.Name} = v;");
            Line($"{target}.Invalidate();");
            _indent--;
            Line("}");
            _out = savedOut;
            _indent = savedIndent;
            _uMethods.Add(new UMethod(name, sb.ToString()));
            Line($"{name}();");
            _renderCalls.Add($"{name}();");
            return;
        }

        var local = $"R{_fnCounter++}";
        var sbLocal = new StringBuilder();
        var savedOutLocal = _out;
        var savedIndentLocal = _indent;
        _out = sbLocal;
        _indent = savedIndentLocal + 1;
        Mapped(uiLine, $"var v = ({type})({expression.Trim()});");
        Line($"if (!global::System.Collections.Generic.EqualityComparer<{type}>.Default.Equals({target}.{p.Name}, v))");
        Line("{");
        _indent++;
        Mapped(uiLine, $"{target}.{p.Name} = v;");
        Line($"{target}.Invalidate();");
        _indent--;
        Line("}");
        _out = savedOutLocal;
        _indent = savedIndentLocal;

        Line($"void {local}()");
        Line("{");
        _out.Append(sbLocal);
        Line("}");
        Line($"{local}();");
        Line($"{ctx.ScopeVar}.AddRenderAction({local});");
    }

    /// <summary>组件内容子节点（§4.12.3）：元素按普通构造，@if/@foreach 生成普通 C# 语句。</summary>
    private void EmitContentChildren(List<UiNode> children, string contentVar, EmitContext ctx)
    {
        foreach (var child in children)
        {
            switch (child)
            {
                case UiElement el:
                    var root = EmitElement(el, parentVar: null, ctx);
                    Line($"{contentVar}.Add({root});");
                    break;
                case UiIf ifNode:
                    EmitPlainIf(ifNode, contentVar, ctx);
                    break;
                case UiForeach foreachNode:
                    EmitPlainForeach(foreachNode, contentVar, ctx);
                    break;
                case UiText:
                    break; // Analyzer 已报 EUI006
            }
        }
    }

    /// <summary>内容内 @if：Build 时按当前值展开的普通 C# if（§4.12.3 规则 7）。</summary>
    private void EmitPlainIf(UiIf node, string contentVar, EmitContext ctx)
    {
        Mapped(LineOf(node.ConditionSpan), $"if ({node.Condition.Trim()})");
        Line("{");
        _indent++;
        EmitContentChildren(node.Children, contentVar, ctx);
        _indent--;
        Line("}");
    }

    /// <summary>内容内 @foreach：Build 时展开的普通 C# foreach（§4.12.3 规则 7）。</summary>
    private void EmitPlainForeach(UiForeach node, string contentVar, EmitContext ctx)
    {
        var fqItem = _itemTypes[node];
        var itemVar = node.VarName.Length > 0 ? node.VarName : "item";
        Mapped(LineOf(node.CollectionSpan), $"foreach (var {itemVar} in {node.Collection.Trim()})");
        Line("{");
        _indent++;
        EmitContentChildren(node.Children, contentVar, ctx);
        _indent--;
        Line("}");
    }

    private void EmitBinding(UiAttribute attr, UiPropDef propDef, string elementVar, EmitContext ctx)
    {
        if (ctx.IsContent) return; // Analyzer 已报 EUI040：内容内不生成绑定
        var expression = attr.Value.Trim();
        var call =
            $"global::EclipseUI.UiBinding.TwoWay({elementVar}, {propDef.DeclaringTypeName}.{propDef.PropertyFieldName}, " +
            $"readTarget: () => {elementVar}.{attr.Name}, writeTarget: v => {elementVar}.{attr.Name} = v, " +
            $"readSource: () => {expression}, writeSource: v => {expression} = v, " +
            "invalidate: Invalidate)";
        int line = LineOf(attr.ValueSpan);

        if (ctx.IsRoot)
        {
            var n = _varCounter++;
            var field = $"__bind{n}";
            _fields.Add(new FieldDecl(n, "bind", "global::EclipseUI.UiBinding"));
            Mapped(line, $"{field} = {call};");
            Line($"Track({field});");
            _renderCalls.Add($"{field}.Refresh();");
            return;
        }

        var local = $"bind{_varCounter++}";
        Mapped(line, $"var {local} = {call};");
        Line($"{ctx.ScopeVar}.AddDisposable({local});");
        BlockRefresh(local, ctx);
    }

    private void EmitContainerChild(UiNode child, string parentVar, EmitContext ctx)
    {
        switch (child)
        {
            case UiElement element:
                EmitElement(element, parentVar, ctx);
                break;
            case UiIf ifNode:
                EmitIf(ifNode, parentVar, ctx);
                break;
            case UiForeach foreachNode:
                EmitForeach(foreachNode, parentVar, ctx);
                break;
            case UiText:
                break; // Analyzer 已报错
        }
    }

    private void EmitTextRuns(UiElement element, string elementVar, EmitContext ctx)
    {
        foreach (var child in element.Children)
        {
            if (child is not UiText text) continue; // Analyzer 已报错
            foreach (var segment in text.Segments)
            {
                if (segment.Kind == TextSegmentKind.Static)
                {
                    Mapped(LineOf(segment.Span),
                        $"((global::EclipseUI.ITextContentHost){elementVar}).AddRun({UiLiterals.EscapeString(segment.Text)});");
                    continue;
                }

                string run;
                if (ctx.IsRoot)
                {
                    var n = _varCounter++;
                    run = $"__run{n}";
                    _fields.Add(new FieldDecl(n, "run", "global::EclipseUI.Elements.TextRun"));
                    Line($"{run} = ((global::EclipseUI.ITextContentHost){elementVar}).AddRun(\"\");");
                }
                else
                {
                    run = NewVar("run");
                    Line($"var {run} = ((global::EclipseUI.ITextContentHost){elementVar}).AddRun(\"\");");
                }

                EmitDynamicUpdate(segment.Text, segment.Span, ctx, $"{run}.Text", interpolate: true);
            }
        }
    }

    private void EmitLabel(UiElement element, string elementVar, UiElementDef def, EmitContext ctx)
    {
        var target = def.ContentTarget;
        if (target is null) return; // 目录缺文本目标（EUI021，C3）

        var segments = element.Children.OfType<UiText>().SelectMany(t => t.Segments).ToList();
        if (segments.Count == 0) return;

        if (segments.All(s => s.Kind == TextSegmentKind.Static))
        {
            var combined = string.Concat(segments.Select(s => s.Text));
            Mapped(LineOf(segments[0].Span), $"{elementVar}.{target} = {UiLiterals.EscapeString(combined)};");
            return;
        }

        var parts = new StringBuilder("$\"");
        foreach (var segment in segments)
        {
            if (segment.Kind == TextSegmentKind.Static)
                parts.Append(EscapeInterpolation(segment.Text));
            else
                parts.Append('{').Append('(').Append(segment.Text.Trim()).Append(')').Append('}');
        }
        parts.Append('"');

        var body = parts.ToString();
        int textLine = LineOf(segments[0].Span);
        if (ctx.IsRoot)
            RootUpdate($"{elementVar}.{target}", body, textLine);
        else
            BlockUpdate($"{elementVar}.{target}", body, textLine, ctx);
    }

    private void EmitDynamicUpdate(string expression, TextSpan span, EmitContext ctx,
        string target, bool interpolate)
    {
        var body = interpolate ? $"$\"{{({expression.Trim()})}}\"" : expression.Trim();
        int line = LineOf(span);

        if (ctx.IsContent)
        {
            // 组件内容是 build-once 快照：直接赋值，不生成 U/R（spec/02 §4.12.3 规则 8）。
            Mapped(line, $"{target} = {body};");
            return;
        }
        if (ctx.IsRoot)
            RootUpdate(target, body, line);
        else
            BlockUpdate(target, body, line, ctx);
    }

    private string EmitIf(UiIf node, string? parentVar, EmitContext ctx)
    {
        bool root = ctx.IsRoot;
        string v;
        if (root)
        {
            var n = _varCounter++;
            v = $"__blk{n}";
            _fields.Add(new FieldDecl(n, "blk", "global::EclipseUI.ConditionalBlock"));
            Line($"{v} = new global::EclipseUI.ConditionalBlock();");
        }
        else
        {
            v = NewVar("blk");
            Line($"var {v} = new global::EclipseUI.ConditionalBlock();");
        }

        if (parentVar is not null)
            Line($"{parentVar}.Children.Add({v});");

        Mapped(LineOf(node.ConditionSpan), $"{v}.SetCondition(() => {node.Condition.Trim()});");

        if (node.Children.Count > 0)
        {
            var scopeVar = NewVar("scope");
            var blockCtx = EmitContext.Block(scopeVar);
            Line($"{v}.SetContent({scopeVar} =>");
            Line("{");
            _indent++;
            var roots = EmitContentRoots(node.Children, blockCtx);
            foreach (var contentRoot in roots)
                Line($"{scopeVar}.AddRoot({contentRoot});");
            _indent--;
            Line("});");
        }

        if (root)
        {
            Line($"Track({v});");
            Line($"{v}.Refresh();");
            _renderCalls.Add($"{v}.Refresh();");
        }
        else
        {
            Line($"{ctx.ScopeVar}.AddDisposable({v});");
            BlockRefresh(v, ctx);
        }

        return v;
    }

    private string EmitForeach(UiForeach node, string? parentVar, EmitContext ctx)
    {
        var fqItem = _itemTypes[node];
        bool root = ctx.IsRoot;
        string v;
        if (root)
        {
            var n = _varCounter++;
            v = $"__blk{n}";
            _fields.Add(new FieldDecl(n, "blk", $"global::EclipseUI.ForEachBlock<{fqItem}>"));
            Line($"{v} = new global::EclipseUI.ForEachBlock<{fqItem}>();");
        }
        else
        {
            v = NewVar("blk");
            Line($"var {v} = new global::EclipseUI.ForEachBlock<{fqItem}>();");
        }

        if (parentVar is not null)
            Line($"{parentVar}.Children.Add({v});");

        Mapped(LineOf(node.CollectionSpan), $"{v}.SetItems(() => {node.Collection.Trim()});");

        var itemVar = node.VarName.Length > 0 ? node.VarName : "item";

        var firstElement = node.Children.OfType<UiElement>().FirstOrDefault();
        var keyAttr = firstElement?.Attributes.FirstOrDefault(a => a.Name == "Key");
        if (keyAttr is not null && !string.IsNullOrWhiteSpace(keyAttr.Value))
        {
            Mapped(LineOf(keyAttr.ValueSpan),
                $"{v}.SetKeySelector(({fqItem} {itemVar}) => (object?)({keyAttr.Value.Trim()}));");
        }

        var scopeVar = NewVar("scope");
        var blockCtx = EmitContext.Block(scopeVar);
        Line($"{v}.SetTemplate(({fqItem} {itemVar}, global::EclipseUI.BlockScope {scopeVar}) =>");
        Line("{");
        _indent++;
        var roots = EmitContentRoots(node.Children, blockCtx);
        foreach (var contentRoot in roots)
            Line($"{scopeVar}.AddRoot({contentRoot});");
        _indent--;
        Line("});");

        if (root)
        {
            Line($"Track({v});");
            Line($"{v}.Refresh();");
            _renderCalls.Add($"{v}.Refresh();");
        }
        else
        {
            Line($"{ctx.ScopeVar}.AddDisposable({v});");
            BlockRefresh(v, ctx);
        }

        return v;
    }

    private List<string> EmitContentRoots(List<UiNode> children, EmitContext ctx)
    {
        var roots = new List<string>();
        foreach (var child in children)
        {
            switch (child)
            {
                case UiElement element:
                    roots.Add(EmitElement(element, parentVar: null, ctx));
                    break;
                case UiIf ifNode:
                    roots.Add(EmitIf(ifNode, parentVar: null, ctx));
                    break;
                case UiForeach foreachNode:
                    roots.Add(EmitForeach(foreachNode, parentVar: null, ctx));
                    break;
            }
        }
        return roots;
    }

    private static string EscapeInterpolation(string s) =>
        s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("{", "{{").Replace("}", "}}");
}
